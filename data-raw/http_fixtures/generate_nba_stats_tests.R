# Regenerate tests/testthat/test-nba_stats_offline.R from nba_stats_calls.txt and the
# responses record_nba_stats.R saved under tests/testthat/fixtures/nba_stats/.
# Run from the package root (offline):
#   Rscript data-raw/http_fixtures/generate_nba_stats_tests.R
#
# Each call is replayed against the fixtures (an unrecorded URL gets a 404) and the
# test asserts what it parsed: the list elements, each data frame's row count, its
# column count, and the names and classes of its first `max_cols` columns. A call
# that returns nothing on its recorded payload (stats.nba.com answers `{}` for the
# retired V2 endpoints) is asserted empty; a defunct wrapper is asserted to signal
# lifecycle's defunctError.

suppressMessages(devtools::load_all(".", quiet = TRUE))
fix_dir <- file.path("tests", "testthat", "fixtures", "nba_stats")
out_file <- file.path("tests", "testthat", "test-nba_stats_offline.R")
max_cols <- 12L
index <- jsonlite::read_json(file.path(fix_dir, "index.json"))

# URLs a call asked for that are not recorded. The wrappers swallow request
# errors, so a miss is tracked here and generation stops before the test file is
# rewritten (an incomplete recording would otherwise look like an empty result).
missed <- character()
replay <- function(req) {
  hit <- index[[req$url]]
  if (is.null(hit)) {
    missed <<- c(missed, req$url)
    return(httr2::response(status_code = 404L, url = req$url))
  }
  path <- file.path(fix_dir, hit$file)
  httr2::response(
    status_code = hit$status, url = req$url, headers = list(`Content-Type` = hit$type),
    body = memDecompress(readBin(path, "raw", file.size(path)), "gzip")
  )
}

dq <- function(x) paste0('"', gsub('"', '\\\\"', x), '"')
vec <- function(x) {
  if (!length(x)) return("character()")
  paste0("c(", paste(dq(x), collapse = ", "), ")")
}
named_vec <- function(x) {
  paste0("c(", paste0("`", names(x), "` = ", dq(x), collapse = ", "), ")")
}
frame_asserts <- function(d, ref) {
  cols <- utils::head(names(d), max_cols)
  classes <- vapply(d[cols], function(v) class(v)[1], "")
  c(
    sprintf("  expect_s3_class(%s, \"data.frame\")", ref),
    sprintf("  expect_equal(nrow(%s), %dL)", ref, nrow(d)),
    sprintf("  expect_gte(ncol(%s), %dL)", ref, ncol(d)),
    # names and classes of the leading columns (indexing a missing column errors)
    if (length(cols)) sprintf("  expect_equal(vapply(%s[%s], function(v) class(v)[1], \"\"),\n    %s)", ref, vec(cols), named_vec(classes))
  )
}

calls <- readLines(file.path("data-raw", "http_fixtures", "nba_stats_calls.txt"))
calls <- trimws(sub("#.*$", "", calls))
calls <- calls[nzchar(calls)]
blocks <- character()
for (call in calls) {
  out <- httr2::with_mocked_responses(replay, tryCatch(
    suppressMessages(suppressWarnings(eval(parse(text = call)))),
    error = function(e) e
  ))
  if (length(missed)) {
    stop("Not recorded (re-run record_nba_stats.R): ", call, " asked for ",
         paste(unique(missed), collapse = ", "), call. = FALSE)
  }
  head <- c(
    sprintf("test_that(%s, {", dq(paste(gsub('"', "'", call), "parses a recorded stats.nba.com response"))),
    "  skip_on_cran()",
    "  local_http_fixtures(dir = \"nba_stats\")"
  )
  body <- if (inherits(out, "defunctError")) {
    head[[1]] <- sprintf("test_that(%s, {", dq(paste(gsub('"', "'", call), "is defunct")))
    # the replay stays on, so a wrapper brought back to life cannot reach the network
    c(head, sprintf("  expect_error(%s, class = \"defunctError\")", call))
  } else if (inherits(out, "error")) {
    message("SKIPPED (errors on its fixture): ", call, ": ", conditionMessage(out))
    next
  } else if (is.data.frame(out)) {
    c(head, sprintf("  x <- suppressMessages(%s)", call),
      if (nrow(out) == 0) "  expect_equal(nrow(x), 0L)" else frame_asserts(out, "x"))
  } else if (is.list(out) && !any(vapply(out, function(d) is.data.frame(d) && nrow(d) > 0, TRUE))) {
    c(head, sprintf("  x <- suppressMessages(%s)", call),
      "  # stats.nba.com answers this retired endpoint with `{}`: no rows come back.",
      "  expect_type(x, \"list\")",
      "  expect_true(all(vapply(x, NROW, integer(1)) == 0L))")
  } else {
    nm <- names(out)
    c(head, sprintf("  x <- suppressMessages(%s)", call),
      sprintf("  expect_named(x, %s)", vec(nm)),
      unlist(lapply(nm, function(n) if (is.data.frame(out[[n]])) frame_asserts(out[[n]], sprintf("x[[%s]]", dq(n))))))
  }
  blocks <- c(blocks, paste(c(body, "})"), collapse = "\n"))
}

header <- c(
  "# Generated by data-raw/http_fixtures/generate_nba_stats_tests.R -- do not edit by hand.",
  "# Each call replays stats.nba.com responses recorded once by",
  "# data-raw/http_fixtures/record_nba_stats.R (see helper-http_fixtures.R), so these",
  "# run offline and on CI and never reach stats.nba.com. Row counts are the recorded",
  "# fixtures' (rowSet arrays are cut to 5 rows when recorded).",
  ""
)
writeLines(c(header, paste(blocks, collapse = "\n\n")), out_file)
message(out_file, ": ", length(blocks), " tests")
