# cli wraps long messages: match a space as any whitespace
g_re <- function(x) gsub(" ", "\\s+", x, fixed = TRUE)

g_path <- function(...) testthat::test_path("fixtures", "genius", ...)

g_text <- function(rel) {
  p <- g_path(rel)
  con <- if (grepl("\\.gz$", p)) gzfile(p, "rb") else file(p, "rb")
  on.exit(close(con))
  x <- rawToChar(readBin(con, "raw", 5e7))
  Encoding(x) <- "UTF-8"
  x
}

g_resp <- function(status = 200L, text = "", headers = list()) {
  httr2::response(status_code = status, url = "https://example.invalid", headers = headers,
                  body = charToRaw(enc2utf8(text)))
}

# Mock the transport: `answer` is one response (or a function of the URL); calls are recorded.
g_mock <- function(answer, env = parent.frame()) {
  calls <- new.env()
  calls$log <- list()
  testthat::local_mocked_bindings(
    .intl_response = function(url, query = list(), ...) {
      calls$log[[length(calls$log) + 1L]] <- list(url = url, query = query, args = list(...))
      if (is.function(answer)) answer(url) else answer
    },
    .env = env, .package = "hoopR"
  )
  calls
}

